// Builds Tempora from src/ into one self-contained file.
//   node build.js   ->  index.html              (full document, open locally)
//                      dist/tempora-artifact.html (body-only, for hosted publishing)
// The Tempora platform server (server/server.js) serves index.html as-is.
const fs = require('fs');
const crypto = require('crypto');
const path = require('path');

const src = f => fs.readFileSync(path.join(__dirname, 'src', f), 'utf8');
const JS_ORDER = [
  'data-core.js', 'data-prehistory.js', 'data-eras1.js', 'data-eras2.js', 'data-eras3.js', 'data-eras4.js', 'data-world.js',
  'data-stats.js', 'data-countries.js', 'data-countries2.js', 'data-regions.js', 'data-extra.js', 'data-life.js',
  'data-map.js', 'data-atlas-arch.js', 'data-faiths.js', 'data-names2.js', 'data-atlas-europe1.js', 'data-atlas-europe2.js', 'data-atlas-europe3.js', 'data-atlas-asia1.js', 'data-atlas-asia2.js', 'data-atlas-asia3.js', 'data-atlas-africa1.js', 'data-atlas-africa2.js', 'data-atlas-africa3.js', 'data-atlas-americas1.js', 'data-atlas-americas2.js', 'data-atlas-oceania.js', 'atlas.js',
  'engine.js', 'engine-player.js', 'genetics.js', 'engine-world.js', 'identity.js', 'faith.js', 'marriage.js', 'net.js', 'personality.js', 'settlements.js', 'society.js', 'politics.js', 'geo.js', 'director.js',
  'ui.js', 'ui2.js', 'ui3.js', 'ui4.js', 'identity-ui.js', 'faith-ui.js', 'net-ui.js', 'map-ui.js', 'director-ui.js', 'dash.js', 'delta.js', 'places.js', 'places2.js', 'household.js', 'auto.js', 'profile.js', 'introduce.js', 'lifedock.js', 'phone.js', 'sports.js',
  'legacy.js', 'ai.js', 'sound.js', 'fusion.js', 'platform.js', 'community.js', 'tree.js', 'late.js', 'main.js',
];

function bundle() { return JS_ORDER.filter(f => fs.existsSync(path.join(__dirname, 'src', f))).map(f => `/* ---- ${f} ---- */\n${src(f)}`).join('\n'); }

function build() {
  const css = ['style.css', 'style2.css', 'style3.css'].filter(f => fs.existsSync(path.join(__dirname, 'src', f))).map(src).join('\n');
  const js = bundle();
  const shell = src('shell.html').replace('/*CSS*/', () => css).replace('/*JS*/', () => js);

  const [head, rest] = shell.replace('<!--DOC-->', '').split('<!--BODY-->');
  const body = rest.replace('<!--END-->', '');

  const full = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
${head.trim()}
</head>
<body>
${body.trim()}
</body>
</html>
`;
  fs.writeFileSync(path.join(__dirname, 'index.html'), full);
  fs.mkdirSync(path.join(__dirname, 'dist'), { recursive: true });
  // Hosted viewers block file downloads, so that build hides the Download button (Copy still works)
  const hosted = body.replace('<script>', '<script>\nwindow.TEMPORA_HOSTED = true;');
  fs.writeFileSync(path.join(__dirname, 'dist', 'tempora-artifact.html'), `${head.trim()}\n${hosted.trim()}\n`);
  // installable app: a manifest and an offline service worker, versioned by the page's own hash
  const hash = crypto.createHash('sha1').update(full).digest('hex').slice(0, 10);
  fs.writeFileSync(path.join(__dirname, 'manifest.webmanifest'), JSON.stringify({
    name: 'Tempora: a life simulator across twelve thousand years', short_name: 'Tempora', description: 'Live one year at a time from 10,000 BC to the far future.',
    start_url: './', scope: './', display: 'standalone', orientation: 'any', background_color: '#E9ECE6', theme_color: '#34469C', categories: ['games', 'simulation'],
    icons: [{ src: 'assets/icon-192.png', sizes: '192x192', type: 'image/png' }, { src: 'assets/icon-512.png', sizes: '512x512', type: 'image/png' }, { src: 'assets/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' }],
  }, null, 2) + '\n');
  fs.writeFileSync(path.join(__dirname, 'sw.js'), `// Tempora service worker: plays offline once the page has loaded once. Generated by build.js.
const CACHE = 'tempora-${hash}';
const CORE = ['./', 'index.html', 'manifest.webmanifest', 'assets/icon-192.png', 'assets/icon-512.png'];
self.addEventListener('install', e => e.waitUntil(caches.open(CACHE).then(c => c.addAll(CORE)).then(() => self.skipWaiting())));
self.addEventListener('activate', e => e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('tempora-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener('fetch', e => {
  const r = e.request, u = new URL(r.url);
  if (r.method !== 'GET' || u.pathname.startsWith('/api/')) return;
  if (u.origin === location.origin) {
    // the page and its files: the network when there is one (so updates arrive), the cache when there is not
    e.respondWith(fetch(r).then(res => { if (res.ok) { const cp = res.clone(); caches.open(CACHE).then(c => c.put(r, cp)); } return res; }).catch(() => caches.match(r).then(m => m || caches.match('index.html'))));
  } else if (/(googleapis|gstatic)\\.com$/.test(u.hostname)) {
    // fonts: whatever is cached, refreshed in the background
    e.respondWith(caches.open(CACHE).then(c => c.match(r).then(m => { const f = fetch(r).then(res => { c.put(r, res.clone()); return res; }).catch(() => m); return m || f; })));
  }
});
`);
  console.log(`index.html ${(full.length / 1024).toFixed(1)} KB`);
}

module.exports = { JS_ORDER, bundle };
if (require.main === module) build();
